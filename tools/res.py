def esc(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    return "\\" + s if s[:1] in "@?" else s


def write(lang):
    i = 1 if lang == "en" else 2
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/res.py; edit the table there. -->", "<resources>"]
    for row in S:
        out.append(f'    <string name="{row[0]}">{esc(row[i])}</string>')
    for k, (en, ru) in A.items():
        out.append(f'    <string-array name="{k}">')
        out += [f"        <item>{esc(x)}</item>" for x in (en if lang == "en" else ru)]
        out.append("    </string-array>")
    for k, (en, ru) in P.items():
        out.append(f'    <plurals name="{k}">')
        if lang == "en":
            out += [f'        <item quantity="one">{en[0]}</item>', f'        <item quantity="other">{en[1]}</item>']
        else:
            out += [f'        <item quantity="{q}">{v}</item>' for q, v in zip(["one", "few", "many", "other"], ru)]
        out.append("    </plurals>")
    out.append("</resources>")
    d = RES / ("values" if lang == "en" else "values-ru")
    d.mkdir(parents=True, exist_ok=True)
    (d / "strings.xml").write_text("\n".join(out) + "\n", encoding="utf-8")


